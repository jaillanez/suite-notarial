# Regla INM: sin borrado; un ejercicio no se modifica; de una fila de puntos solo cambia el
# vínculo con el padrón (lo demás es el dato del origen).
GUARD_FN = """
CREATE OR REPLACE FUNCTION previsional_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP IN ('DELETE', 'TRUNCATE') THEN
        RAISE EXCEPTION '%: % no permitido (sin borrado físico, regla INM)', TG_TABLE_NAME, TG_OP
            USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF TG_TABLE_NAME = 'previsional_ejercicios' THEN
        RAISE EXCEPTION 'previsional_ejercicios: un ejercicio cargado no se modifica'
            USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF (NEW.id, NEW.ejercicio_id, NEW.nombre_origen, NEW.aportes, NEW.puntos, NEW.origen,
        NEW.fila_origen, NEW.created_by_user_id, NEW.created_at)
       IS DISTINCT FROM
       (OLD.id, OLD.ejercicio_id, OLD.nombre_origen, OLD.aportes, OLD.puntos, OLD.origen,
        OLD.fila_origen, OLD.created_by_user_id, OLD.created_at) THEN
        RAISE EXCEPTION 'previsional_puntos: los aportes y puntos cargados no se modifican; solo el vínculo con el padrón'
            USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
END;
$$;
"""


def _revoke_from_app_roles(table: str, privileges: str) -> None:
    op.execute(
        f"""
        DO $$
        DECLARE grantee_name text;
        BEGIN
            FOR grantee_name IN
                SELECT DISTINCT grantee FROM information_schema.role_table_grants
                WHERE table_schema = 'public' AND table_name = '{table}'
                  AND grantee <> current_user
            LOOP
                EXECUTE format('REVOKE {privileges} ON {table} FROM %I', grantee_name);
            END LOOP;
        END
        $$;
        """
    )


