GUARD_PAGADA_ANTES = """
CREATE OR REPLACE FUNCTION pagos_boleta_pagada_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.estado = 'PAGADA' AND OLD.estado IS DISTINCT FROM 'PAGADA'
       AND NOT EXISTS (
           SELECT 1 FROM pagos_conciliaciones
           WHERE boleta_id = NEW.id AND resultado = 'APROBADO'
       ) THEN
        RAISE EXCEPTION 'ddjj_boletas: una boleta pasa a PAGADA solo con una conciliación aprobada'
            USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
END;
$$;
"""

# Pagada = lo conciliado + créditos - débitos aprobados cubre el total exacto, con al menos una
# conciliación aprobada o un ajuste aprobado que la respalde.
GUARD_PAGADA_AHORA = """
CREATE OR REPLACE FUNCTION pagos_boleta_pagada_guard() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    conciliado numeric(15, 2);
    ajustado numeric(15, 2);
    con_respaldo boolean;
BEGIN
    IF NEW.estado = 'PAGADA' AND OLD.estado IS DISTINCT FROM 'PAGADA' THEN
        SELECT coalesce(sum(importe_confirmado), 0), count(*) > 0 INTO conciliado, con_respaldo
        FROM pagos_conciliaciones WHERE boleta_id = NEW.id AND resultado = 'APROBADO';
        SELECT coalesce(sum(CASE WHEN tipo = 'CREDITO' THEN importe ELSE -importe END), 0),
               con_respaldo OR count(*) > 0
        INTO ajustado, con_respaldo
        FROM pagos_ajustes WHERE boleta_id = NEW.id AND estado = 'APROBADO';
        IF NOT con_respaldo OR conciliado + ajustado <> NEW.total_a_pagar THEN
            RAISE EXCEPTION 'ddjj_boletas: una boleta pasa a PAGADA cuando lo conciliado más '
                'los ajustes aprobados cubre el total'
                USING ERRCODE = 'insufficient_privilege';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
"""


